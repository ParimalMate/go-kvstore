#!/usr/bin/env python3
"""Run the chaos harness over several seeds and print a Markdown results table.

  python3 scripts/chaos-matrix.py --seeds 1-10 --duration 60 > docs/chaos-results.md

Every number comes from the harness's own summary.json files, never typed by hand.
Exit code is non-zero if any seed reported a violation or the harness itself failed.
"""
import argparse
import datetime
import json
import os
import platform
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def parse_seeds(text):
    seeds = []
    for part in text.split(","):
        if "-" in part:
            low, high = part.split("-", 1)
            seeds.extend(range(int(low), int(high) + 1))
        else:
            seeds.append(int(part))
    return seeds


def command_output(*cmd):
    try:
        return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:
        return "unknown"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--seeds", default="1-10")
    p.add_argument("--duration", type=float, default=60.0)
    p.add_argument("--out", default="chaos-results")
    p.add_argument("--no-race", action="store_true")
    args = p.parse_args()

    rows, failed = [], False
    for seed in parse_seeds(args.seeds):
        cmd = [sys.executable, str(HERE / "chaos-cluster.py"), "--seed", str(seed),
               "--duration", str(args.duration), "--out", args.out]
        if args.no_race:
            cmd.append("--no-race")
        print(f"running seed {seed} ...", file=sys.stderr, flush=True)
        code = subprocess.run(cmd, cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode
        summary_path = Path(ROOT / args.out / f"seed-{seed}" / "summary.json")
        if not summary_path.exists():
            rows.append(f"| {seed} | {args.duration:g}s | harness error (exit {code}) | | | | | | |")
            failed = True
            continue
        s = json.loads(summary_path.read_text())
        counts = s["counts"]
        faults = sum(n for action, n in s.get("faults", {}).items()
                     if action in ("kill", "pause", "bounce", "cut", "oneway", "slow"))
        reads = sum(v for k, v in counts.items() if k.startswith("get_") and k not in ("get_error",))
        failed |= s["violation_count"] != 0 or code != 0
        rows.append("| {seed} | {dur:g}s | {faults} | {acked} | {indet} | {reads} | {conf} | {replay} | {viol} |".format(
            seed=seed, dur=args.duration, faults=faults, acked=counts.get("put_acked", 0),
            indet=counts.get("put_indeterminate", 0), reads=reads, conf=f"{s.get('convergence_seconds', '?')}s",
            replay="yes" if s.get("replay_identical") else "NO", viol=s["violation_count"]))

    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    print("# Chaos results\n")
    print("Generated by `scripts/chaos-matrix.py`; every number comes from the harness's summary files.\n")
    print(f"- Date: {now}")
    print(f"- Machine: {platform.platform()}, {os.cpu_count()} CPU(s), Python {platform.python_version()}")
    print(f"- {command_output('go', 'version')}")
    print(f"- Commit: {command_output('git', 'rev-parse', '--short', 'HEAD')}")
    print(f"- Server built with the race detector: {'no' if args.no_race else 'yes (a data race fails the run)'}\n")
    print("| Seed | Chaos | Faults injected | Writes acked | Writes indeterminate | Reads answered | Convergence | Replay identical | Violations |")
    print("|---|---|---|---|---|---|---|---|---|")
    print("\n".join(rows))
    print("\nA seed replays the fault schedule and each writer's operation sequence; real-process timing means "
          "the exact interleaving can differ between runs of the same seed.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
